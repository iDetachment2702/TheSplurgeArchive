ダンボールがたまりにたまっているので、効率的に縛る手順を考えた。

ダンボールを縛るときの難点は、

- 縛るときにひっくり返したり、
- 紐を繰るのが地味に難しいこと

この2点を解消するためにカッターとストッカーを導入した。

- ストッカーがあればひっくり返さずに縛る作業ができる
- 貫通カッターを使えば以下の手順で簡単に縛ることができる
  - カッターでダンボールを貫通する
  - カッターの先端に紐を引っかけ、引き抜く
  - 紐をダンボールの端で結ぶ

素早く安定してダンボールを縛ることができた。

重ねる枚数は薄い方が楽なので定期的に縛っていくようにしよう。
